const sleep = ms => new Promise(r => setTimeout(r, ms));

async function fetchPexelsPhoto(query) {
  const res = await fetch(
    `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=5&orientation=landscape`,
    { headers: { Authorization: PEXELS_API_KEY } }
  );
  if (!res.ok) throw new Error(`Pexels ${res.status}`);
  const data = await res.json();
  if (!data.photos?.length) throw new Error(`No results: ${query}`);
  return data.photos[0];
}

async function uploadPhoto(photo, suffix) {
  const imgUrl = photo.src.large2x ?? photo.src.large;
  const ext = (imgUrl.split('?')[0].split('.').pop() || 'jpg').toLowerCase();
  const filename = `pexels-photo-${photo.id}-ppc-${suffix}.${ext}`;
  const buf = await (await fetch(imgUrl)).arrayBuffer();
  const fd = new FormData();
  fd.append('file', new Blob([buf], { type: ext === 'jpg' || ext === 'jpeg' ? 'image/jpeg' : `image/${ext}` }), filename);
  const res = await fetch(`https://${MICROCMS_DOMAIN}.microcms-management.io/api/v1/media`, {
    method: 'POST',
    headers: { 'X-MICROCMS-API-KEY': MICROCMS_API_KEY },
    body: fd,
  });
  if (!res.ok) throw new Error(`Upload failed ${res.status}: ${await res.text()}`);
  const data = await res.json();
  return { url: data.url, credit: photo.photographer };
}

